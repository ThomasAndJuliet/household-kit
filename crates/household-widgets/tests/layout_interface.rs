//! The layout engine's public interface, frozen.
//!
//! What it is for. `household_widgets::layout` is used by every household
//! app and by most widgets in this crate, and its code is being rebuilt
//! behind an interface that must not change. This file names every item a
//! caller outside the crate can reach through the layout modules
//! (`layout.rs`, `layout_frame.rs`, `layout_presentation.rs`,
//! `layout_information.rs`, `layout_navigation.rs`, `layout_popup.rs`,
//! `layout_hover.rs`), by the path a caller uses, with its exact shape:
//!
//! - a function or method is coerced to its function-pointer type; where it
//!   takes an `impl Trait` argument it is called from a wrapper whose own
//!   signature states the bounds and the return type;
//! - a struct's public fields are read with their types; a struct whose
//!   fields are all public is also destructured and built with a literal,
//!   so a field added or removed fails too;
//! - an enum is matched exhaustively, with no wildcard arm, every variant
//!   with its fields;
//! - the traits callers rely on (the derives, the hand-written impls, and
//!   `Send`/`Sync` where they hold today) are required by a bound;
//! - `Level::ALL` is pinned by type and value, and `Level`'s variant order,
//!   which its derived `Ord` follows, by discriminant.
//!
//! Nothing here runs: the file is a compile-time check and holds no
//! behaviour tests. Every function in it is called nowhere, hence
//! `dead_code` is allowed; the function-pointer types are long by nature,
//! hence `type_complexity`.
//!
//! How to read a failure. If this file stops compiling, the interface has
//! changed. The error points at the item; the comment above it gives the
//! source file and line where the item was declared when the file was
//! written. A rename or removal fails at the `use` or the path; a changed
//! signature fails at the coercion or the wrapper's call; a new, removed or
//! reshaped variant fails at its `match`; a lost trait fails at the bound.
//! Undo the change in the engine; do not edit this file to make it compile.
//!
//! The rule. This file changes only when Juliet agrees a change to the
//! interface, and then in the same commit as that change. Source line
//! numbers in the comments may be refreshed at any time.

